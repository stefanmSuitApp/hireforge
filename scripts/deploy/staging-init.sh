#!/usr/bin/env bash
# Runs ON THE SERVER. Safe to re-run.
#
# 1. Once: deploy/.env.staging from deploy/.env.production, with its own
#    secrets and database/Redis passwords, the staging origin, and nothing
#    that reaches the outside world: no email (empty RESEND_API_KEY), no CMS
#    writes, no object storage, no search-engine pings, billing test mode.
#    An existing file is kept (its passwords initialised the staging volumes).
# 2. Every run: once STAGING_HOST resolves to this server (same address as
#    sljakam.com), deploy/caddy-sites/staging.caddy puts it behind basic auth
#    on production's Caddy, validated before Caddy reloads.
#
#   ./scripts/deploy/staging-init.sh
#
# The basic-auth login is in deploy/.env.staging:
#   grep STAGING_BASIC_AUTH deploy/.env.staging
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$ROOT"
PROD_ENV=deploy/.env.production
STAGING_ENV=deploy/.env.staging
SITE=deploy/caddy-sites/staging.caddy
STAGING_HOST=${STAGING_HOST:-staging.sljakam.com}
secret() { openssl rand -hex 32; }
get() { grep -E "^$1=" "$2" | tail -1 | cut -d= -f2-; }

if [[ ! -f $STAGING_ENV ]]; then
  pg_user=$(get POSTGRES_USER "$PROD_ENV")
  pg_pw=$(secret)
  redis_pw=$(secret)
  origin="https://$STAGING_HOST"
  overrides=(
    "POSTGRES_DB=hireforge_staging"
    "POSTGRES_PASSWORD=$pg_pw"
    "DATABASE_URL=postgresql://$pg_user:$pg_pw@postgres:5432/hireforge_staging"
    "REDIS_PASSWORD=$redis_pw"
    "REDIS_URL=redis://:$redis_pw@redis:6379"
    "AUTH_JWT_SECRET=$(secret)"
    "CMS_SYNC_SECRET=$(secret)"
    "SANITY_WEBHOOK_SECRET=$(secret)"
    "SANITY_API_WRITE_TOKEN="
    "NEXT_PUBLIC_APP_URL=$origin"
    "SITE_ORIGIN=$origin"
    "APP_PUBLIC_ORIGIN=$origin"
    "BILLING_EMAIL_DASHBOARD_ORIGIN=$origin"
    "RESEND_API_KEY="
    "BILLING_EMAIL_TEST_TO="
    "BILLING_TEST_MODE=1"
    "AWS_ACCESS_KEY_ID="
    "AWS_SECRET_ACCESS_KEY="
    "S3_JOB_MEDIA_BUCKET="
    "S3_BILLING_BUCKET="
    "S3_BACKUP_BUCKET="
    "INDEXNOW_KEY="
    "GOOGLE_INDEXING_SA_JSON="
    "GOOGLE_SITE_VERIFICATION="
    "BING_SITE_VERIFICATION="
    "YANDEX_SITE_VERIFICATION="
    "INTEGRATION_API_URL="
    "JOB_DESCRIPTION_MEDIA_PUBLIC_ORIGIN="
    "STAGING_BASIC_AUTH_USER=sljakam"
    "STAGING_BASIC_AUTH_PASSWORD=$(openssl rand -base64 18 | tr -d '/+=')"
  )
  keys=$(printf '%s\n' "${overrides[@]}" | cut -d= -f1 | paste -sd'|')
  umask 077
  {
    echo "# Staging env, generated by scripts/deploy/staging-init.sh on $(date -u +%F)."
    echo "# Copied from .env.production minus everything below; never commit."
    grep -vE "^($keys)=" "$PROD_ENV"
    echo
    echo "# --- staging overrides ---"
    printf '%s\n' "${overrides[@]}"
  } >"$STAGING_ENV"
  echo "wrote $STAGING_ENV (login: grep STAGING_BASIC_AUTH $STAGING_ENV)"
else
  echo "$STAGING_ENV exists; kept"
fi

mkdir -p deploy/caddy-sites
want=$(getent ahostsv4 sljakam.com | awk '{ print $1; exit }')
have=$(getent ahostsv4 "$STAGING_HOST" | awk '{ print $1; exit }' || true)
if [[ -z $have || $have != "$want" ]]; then
  echo "$STAGING_HOST does not resolve to this server ($want) yet: add a DNS A record, then re-run"
  rm -f "$SITE"
  exit 0
fi

user=$(get STAGING_BASIC_AUTH_USER "$STAGING_ENV")
hash=$(docker compose -f compose.prod.yml exec -T caddy caddy hash-password \
  --plaintext "$(get STAGING_BASIC_AUTH_PASSWORD "$STAGING_ENV")")
cat >"$SITE" <<EOF
# Generated by scripts/deploy/staging-init.sh; never commit.
$STAGING_HOST {
	basic_auth {
		$user $hash
	}
	header {
		-Server
		X-Robots-Tag "noindex, nofollow"
	}
	reverse_proxy staging-web:3000
}
EOF
if docker compose -f compose.prod.yml exec -T caddy caddy validate --config /etc/caddy/Caddyfile >/dev/null 2>&1; then
  docker compose -f compose.prod.yml exec -T caddy caddy reload --config /etc/caddy/Caddyfile >/dev/null
  echo "Caddy serves https://$STAGING_HOST (basic auth user: $user)"
else
  rm -f "$SITE"
  echo "Caddy rejected the staging site; removed it, production config unchanged" >&2
  exit 1
fi
