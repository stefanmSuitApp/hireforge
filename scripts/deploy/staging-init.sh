#!/usr/bin/env bash
# Runs ON THE SERVER, from staging's checkout (/opt/hireforge-staging). Safe
# to re-run; release.sh runs it with --env-only before every staging release.
#
# 1. Once: deploy/.env.staging from production's env with staging's own
#    secrets (login signing, CMS sync, webhook), database/Redis passwords and
#    origin, billing in test mode, no CMS writes and no search-engine pings.
#    An existing file is kept (its passwords initialised the staging volumes).
# 2. Every run: the keys staging shares with production are copied over again
#    (so a rotation on production reaches staging on its next deploy): the
#    Sanity project, dataset and read token, the bucket keys (dumps under backups/postgres/staging/)
#    and the Resend key, the latter only with EMAIL_REDIRECT_TO set: every
#    staging email goes to that one inbox.
# 3. Unless --env-only: once STAGING_HOST resolves to this server (same address
#    as sljakam.com), production's Caddy serves it
#    (deploy/caddy-sites/staging.caddy in production's checkout, validated
#    before Caddy reloads), always with `X-Robots-Tag: noindex`. Open by
#    default (Stefan, 2026-10-29); a basic-auth login only when
#    STAGING_BASIC_AUTH_PASSWORD is set in deploy/.env.staging.
#
#   STAGING_EMAIL_TO=you@example.com ./scripts/deploy/staging-init.sh
#
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$ROOT"
PROD_ROOT=${HIREFORGE_PROD_ROOT:-/opt/hireforge}
PROD_ENV=$PROD_ROOT/deploy/.env.production
STAGING_ENV=deploy/.env.staging
SITE=$PROD_ROOT/deploy/caddy-sites/staging.caddy
STAGING_HOST=${STAGING_HOST:-staging.sljakam.com}
# The Sanity token only works with its project: they move together (the move
# to project o85214ma on 2026-10-29 left staging with the new token and the
# old project).
SHARED_KEYS=(SANITY_API_READ_TOKEN SANITY_PROJECT_ID SANITY_DATASET
  NEXT_PUBLIC_SANITY_PROJECT_ID NEXT_PUBLIC_SANITY_DATASET
  SANITY_STUDIO_PROJECT_ID SANITY_STUDIO_DATASET
  RESEND_API_KEY AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY
  S3_ENDPOINT S3_REGION S3_FORCE_PATH_STYLE S3_BACKUP_BUCKET)
secret() { openssl rand -hex 32; }
get() { grep -E "^$1=" "$2" | tail -1 | cut -d= -f2- || true; }
[[ -f $PROD_ENV ]] || { echo "no $PROD_ENV (HIREFORGE_PROD_ROOT=$PROD_ROOT)" >&2; exit 1; }

# Replaces or appends KEY=value lines in $STAGING_ENV; values never printed.
set_env() {
  local tmp
  tmp=$(mktemp "$STAGING_ENV.XXXXXX")
  awk -F= 'NR == FNR { v[$1] = $0; next }
    ($1 in v) { if (!done[$1]++) print v[$1]; next }
    { print }
    END { for (k in v) if (!done[k]) print v[k] }' <(printf '%s\n' "$@") "$STAGING_ENV" >"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$STAGING_ENV"
}

umask 077
if [[ ! -f $STAGING_ENV ]]; then
  pg_user=$(get POSTGRES_USER "$PROD_ENV")
  pg_pw=$(secret)
  redis_pw=$(secret)
  origin="https://$STAGING_HOST"
  overrides=(
    "POSTGRES_DB=hireforge_staging"
    "POSTGRES_PASSWORD=$pg_pw"
    "DATABASE_URL=postgresql://$pg_user:$pg_pw@postgres:5432/hireforge_staging"
    "REDIS_PASSWORD=$redis_pw"
    "REDIS_URL=redis://:$redis_pw@redis:6379"
    "AUTH_JWT_SECRET=$(secret)"
    "CMS_SYNC_SECRET=$(secret)"
    "SANITY_WEBHOOK_SECRET=$(secret)"
    "SANITY_API_WRITE_TOKEN="
    "NEXT_PUBLIC_APP_URL=$origin"
    "SITE_ORIGIN=$origin"
    "APP_PUBLIC_ORIGIN=$origin"
    "BILLING_EMAIL_DASHBOARD_ORIGIN=$origin"
    "BILLING_EMAIL_TEST_TO="
    "BILLING_TEST_MODE=1"
    "S3_JOB_MEDIA_BUCKET="
    "S3_BILLING_BUCKET="
    "INDEXNOW_KEY="
    "GOOGLE_INDEXING_SA_JSON="
    "GOOGLE_SITE_VERIFICATION="
    "BING_SITE_VERIFICATION="
    "YANDEX_SITE_VERIFICATION="
    "INTEGRATION_API_URL="
    "JOB_DESCRIPTION_MEDIA_PUBLIC_ORIGIN="
    "STAGING_BASIC_AUTH_USER=sljakam"
    "STAGING_BASIC_AUTH_PASSWORD="
  )
  keys=$(printf '%s\n' "${overrides[@]}" | cut -d= -f1 | paste -sd'|')
  {
    echo "# Staging env, generated by scripts/deploy/staging-init.sh on $(date -u +%F)."
    echo "# Copied from .env.production minus everything below; never commit."
    grep -vE "^($keys)=" "$PROD_ENV"
    echo
    echo "# --- staging overrides ---"
    printf '%s\n' "${overrides[@]}"
  } >"$STAGING_ENV"
  echo "wrote $STAGING_ENV"
fi

shared=()
for k in "${SHARED_KEYS[@]}"; do shared+=("$k=$(get "$k" "$PROD_ENV")"); done
shared+=("S3_BACKUP_PREFIX=backups/postgres/staging/")
redirect=${STAGING_EMAIL_TO:-$(get EMAIL_REDIRECT_TO "$STAGING_ENV")}
if [[ -n $redirect ]]; then
  shared+=("EMAIL_REDIRECT_TO=$redirect")
else
  # No inbox to redirect to: staging sends no email at all.
  shared+=("RESEND_API_KEY=")
  echo "no EMAIL_REDIRECT_TO (set STAGING_EMAIL_TO once): staging sends no email"
fi
set_env "${shared[@]}"
echo "$STAGING_ENV: shared keys copied from production"

[[ ${1:-} == --env-only ]] && exit 0

mkdir -p "$(dirname "$SITE")"
want=$(getent ahostsv4 sljakam.com | awk '{ print $1; exit }')
have=$(getent ahostsv4 "$STAGING_HOST" | awk '{ print $1; exit }' || true)
if [[ -z $have || $have != "$want" ]]; then
  echo "$STAGING_HOST does not resolve to this server ($want) yet: add a DNS A record, then re-run"
  rm -f "$SITE"
  exit 0
fi

caddy() { docker compose -f "$PROD_ROOT/compose.prod.yml" exec -T caddy caddy "$@"; }
user=$(get STAGING_BASIC_AUTH_USER "$STAGING_ENV")
password=$(get STAGING_BASIC_AUTH_PASSWORD "$STAGING_ENV")
login=
if [[ -n $user && -n $password ]]; then
  login=$(printf '\tbasic_auth {\n\t\t%s %s\n\t}\n' "$user" "$(caddy hash-password --plaintext "$password")")
fi
cat >"$SITE" <<EOF
# Generated by scripts/deploy/staging-init.sh; never commit.
$STAGING_HOST {
$login
	header {
		-Server
		X-Robots-Tag "noindex, nofollow"
	}
	reverse_proxy staging-web:3000
}
EOF
if caddy validate --config /etc/caddy/Caddyfile >/dev/null 2>&1; then
  caddy reload --config /etc/caddy/Caddyfile >/dev/null
  echo "Caddy serves https://$STAGING_HOST (${login:+basic auth user: $user}${login:-open, noindex})"
else
  rm -f "$SITE"
  echo "Caddy rejected the staging site; removed it, production config unchanged" >&2
  exit 1
fi
